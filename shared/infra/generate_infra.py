"""Regenerates docker-compose.yml, nginx.conf and postgres/init.sql from the app list.

Run from anywhere:  python shared/infra/generate_infra.py
Add an app by appending to APPS (and creating <slug>/backend and <slug>/frontend).
"""

from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent


@dataclass(frozen=True)
class App:
    slug: str
    title: str
    description: str
    volume: bool = False  # persistent /data mount (uploads)
    websocket: bool = False
    needs_origin: bool = False  # backend checks the WebSocket Origin
    max_body: str = ""  # nginx client_max_body_size override for the API location
    streaming: bool = False  # large uploads / range streaming: no request buffering


APPS: tuple[App, ...] = (
    App("chat", "Chat", "Talk in rooms in real time", websocket=True, needs_origin=True),
    App("photos", "Photos", "Share and like photos", volume=True, max_body="6m"),
    App("watch", "Watch", "Upload and watch videos", volume=True, max_body="110m", streaming=True),
    App("werewolf", "Werewolf", "Play the social-deduction game", websocket=True, needs_origin=True),
    App("market", "Market", "Buy and sell products"),
    App("learning", "Learning", "Take and teach skill courses"),
    App("jobs", "Jobs", "Find work or hire people"),
)

PROXY_HEADERS = """        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto $scheme;
"""


def compose() -> str:
    services = []
    for app in APPS:
        env = ["      <<: *backend-env",
               f"      DATABASE_URL: postgresql+psycopg://postgres:${{POSTGRES_PASSWORD}}@postgres:5432/{app.slug}"]
        if app.needs_origin:
            env.append("      ALLOWED_ORIGINS: ${PUBLIC_ORIGIN:-http://localhost:8080}")
        backend = [
            f"  {app.slug}-backend:",
            "    <<: *hardening",
            "    build:",
            "      context: ../..",
            f"      dockerfile: {app.slug}/backend/Dockerfile",
            "    environment:",
            *env,
            "    depends_on:",
            "      postgres:",
            "        condition: service_healthy",
        ]
        if app.volume:
            backend += ["    volumes:", f"      - {app.slug}-data:/data"]
        frontend = [
            f"  {app.slug}-frontend:",
            "    <<: *hardening",
            "    build:",
            "      context: ../..",
            f"      dockerfile: {app.slug}/frontend/Dockerfile",
        ]
        services.append("\n".join(backend))
        services.append("\n".join(frontend))

    gateway_deps = ["      - center-backend", "      - center-frontend"]
    for app in APPS:
        gateway_deps += [f"      - {app.slug}-backend", f"      - {app.slug}-frontend"]
    volumes = ["  pgdata:"] + [f"  {app.slug}-data:" for app in APPS if app.volume]

    return f"""name: socialnetwork

# GENERATED by shared/infra/generate_infra.py - edit APPS there, not this file.
# Run from the repo root:
#   docker compose --env-file .env -f shared/infra/docker-compose.yml up --build

x-hardening: &hardening
  cap_drop: [ALL]
  security_opt: ["no-new-privileges:true"]
  restart: unless-stopped

x-backend-env: &backend-env
  JWT_SECRET: ${{JWT_SECRET:?set JWT_SECRET in .env (32+ characters)}}
  COOKIE_SECURE: ${{COOKIE_SECURE:-0}}

services:
  postgres:
    image: postgres:17-alpine
    environment:
      POSTGRES_PASSWORD: ${{POSTGRES_PASSWORD:?set POSTGRES_PASSWORD in .env}}
    volumes:
      - pgdata:/var/lib/postgresql/data
      - ./postgres/init.sql:/docker-entrypoint-initdb.d/init.sql:ro
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U postgres"]
      interval: 5s
      timeout: 3s
      retries: 10

  center-backend:
    <<: *hardening
    build:
      context: ../..
      dockerfile: center/backend/Dockerfile
    environment:
      <<: *backend-env
      DATABASE_URL: postgresql+psycopg://postgres:${{POSTGRES_PASSWORD}}@postgres:5432/center
    depends_on:
      postgres:
        condition: service_healthy

  center-frontend:
    <<: *hardening
    build:
      context: ../..
      dockerfile: center/frontend/Dockerfile

{chr(10).join(s + chr(10) for s in services)}
  gateway:
    <<: *hardening
    # nginx needs CHOWN/SETUID/SETGID/NET_BIND_SERVICE at start-up; keep its
    # default capabilities instead of guessing the minimal set untested.
    cap_drop: []
    image: nginx:1.27-alpine
    ports:
      - "${{GATEWAY_PORT:-8080}}:80"
    volumes:
      - ./nginx.conf:/etc/nginx/conf.d/default.conf:ro
    depends_on:
{chr(10).join(gateway_deps)}

volumes:
{chr(10).join(volumes)}
"""


def api_location(app: App) -> str:
    lines = [f"    location /api/{app.slug}/ {{"]
    if app.max_body:
        lines.append(f"        client_max_body_size {app.max_body};")
    if app.streaming:
        lines += [
            "        proxy_request_buffering off;  # stream uploads to the backend",
            "        proxy_buffering off;          # stream video ranges back",
            "        proxy_read_timeout 1h;",
            "        proxy_send_timeout 1h;",
        ]
    if app.websocket:
        lines += [
            "        proxy_http_version 1.1;",
            "        proxy_set_header Upgrade $http_upgrade;",
            "        proxy_set_header Connection $connection_upgrade;",
            "        proxy_read_timeout 1h;",
        ]
    lines.append(f"        proxy_pass http://{app.slug}-backend:8000/;")
    lines.append(PROXY_HEADERS.rstrip("\n"))
    lines.append("    }")
    return "\n".join(lines)


def frontend_location(app: App) -> str:
    return f"""    location ~ ^/{app.slug}(/|$) {{
        proxy_pass http://{app.slug}-frontend:3000;
        proxy_set_header Host $host;
    }}"""


def nginx() -> str:
    api = "\n\n".join(api_location(app) for app in APPS)
    frontends = "\n\n".join(frontend_location(app) for app in APPS)
    return f"""# GENERATED by shared/infra/generate_infra.py - edit APPS there, not this file.
# Single public entry point. Everything is same-origin, so the auth cookie is
# HttpOnly and no CORS is needed.

map $http_upgrade $connection_upgrade {{
    default upgrade;
    ''      close;
}}

# Brute-force guard for credential endpoints (the backends also throttle).
limit_req_zone $binary_remote_addr zone=auth:10m rate=10r/m;

server {{
    listen 80;
    server_name _;
    server_tokens off;
    client_max_body_size 1m;

    add_header X-Content-Type-Options "nosniff" always;
    add_header X-Frame-Options "DENY" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;

    # --- center: the prefix is stripped before reaching the service ---
    location /api/center/auth/ {{
        limit_req zone=auth burst=10 nodelay;
        limit_req_status 429;
        proxy_pass http://center-backend:8000/auth/;
{PROXY_HEADERS.rstrip(chr(10))}
    }}

    location /api/center/ {{
        proxy_pass http://center-backend:8000/;
{PROXY_HEADERS.rstrip(chr(10))}
    }}

    # --- app APIs ---
{api}

    # --- app frontends (each served under /<slug>) ---
{frontends}

    # --- shell (center frontend) ---
    location / {{
        proxy_pass http://center-frontend:3000;
        proxy_set_header Host $host;
    }}
}}
"""


def init_sql() -> str:
    names = ["center"] + [app.slug for app in APPS]
    statements = "\n".join(f"CREATE DATABASE {name};" for name in names)
    return f"-- GENERATED by generate_infra.py. One database per service; services never read each other's tables.\n{statements}\n"


def apps_ts() -> str:
    entries = "\n".join(
        f'  {{ name: "{app.title}", href: "/{app.slug}", description: "{app.description}" }},'
        for app in APPS
    )
    return f"""export interface AppLink {{
  name: string;
  href: string;
  description: string;
}}

/** Every app mounted behind the gateway. Generated by shared/infra/generate_infra.py. */
export const APPS: readonly AppLink[] = [
{entries}
];
"""


def main() -> None:
    (HERE / "docker-compose.yml").write_text(compose(), encoding="utf-8", newline="\n")
    (HERE / "nginx.conf").write_text(nginx(), encoding="utf-8", newline="\n")
    (HERE / "postgres" / "init.sql").write_text(init_sql(), encoding="utf-8", newline="\n")
    (REPO / "center" / "frontend" / "app" / "apps.ts").write_text(apps_ts(), encoding="utf-8", newline="\n")
    print("generated compose, nginx, init.sql, apps.ts for:", ", ".join(app.slug for app in APPS))


if __name__ == "__main__":
    main()
